/**
 * Prioritizes events into LOW, MEDIUM, and HIGH queues.
 */

export const PRIORITY_LEVELS = {
  LOW: 'LOW',
  MEDIUM: 'MEDIUM',
  HIGH: 'HIGH'
};

const PRIORITY_MAP = {
  // HIGH PRIORITY
  'SQL_INJECTION': PRIORITY_LEVELS.HIGH,
  'DOM_TAMPERING': PRIORITY_LEVELS.HIGH,
  'HEADLESS_BROWSER': PRIORITY_LEVELS.HIGH,
  'JS_INTEGRITY_FAILURE': PRIORITY_LEVELS.HIGH,
  'DEVTOOLS_OPENED': PRIORITY_LEVELS.HIGH,
  'BROWSER_AUTOMATION': PRIORITY_LEVELS.HIGH,
  'SECURITY_ALERT': PRIORITY_LEVELS.HIGH,

  // MEDIUM PRIORITY
  'PAGE_NAVIGATION': PRIORITY_LEVELS.MEDIUM,
  'LOGIN_ATTEMPT': PRIORITY_LEVELS.MEDIUM,
  'LOGIN_SUCCESS': PRIORITY_LEVELS.MEDIUM,
  'LOGIN_FAILED': PRIORITY_LEVELS.MEDIUM,
  'FINGERPRINT_REFRESH': PRIORITY_LEVELS.MEDIUM,
  'API_REQUEST': PRIORITY_LEVELS.MEDIUM,
  'API_RESPONSE': PRIORITY_LEVELS.MEDIUM,
  'API_ERROR': PRIORITY_LEVELS.MEDIUM,
  'FORM_SUBMISSION': PRIORITY_LEVELS.MEDIUM,
  'session_start': PRIORITY_LEVELS.MEDIUM,
  'session_end': PRIORITY_LEVELS.MEDIUM,

  // LOW PRIORITY (Default for anything else not matching above)
  'MOUSE_ACTIVITY': PRIORITY_LEVELS.LOW,
  'CLICK_ACTIVITY': PRIORITY_LEVELS.LOW,
  'SCROLL_ACTIVITY': PRIORITY_LEVELS.LOW,
  'KEYBOARD_ACTIVITY': PRIORITY_LEVELS.LOW,
  'HOVER': PRIORITY_LEVELS.LOW,
  'RESIZE': PRIORITY_LEVELS.LOW,
  'FOCUS': PRIORITY_LEVELS.LOW,
  'BLUR': PRIORITY_LEVELS.LOW,
  'IDLE': PRIORITY_LEVELS.LOW
};

export function getEventPriority(eventType) {
  return PRIORITY_MAP[eventType] || PRIORITY_LEVELS.LOW;
}
